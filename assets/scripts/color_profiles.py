def c_header():
    lines = ['/* Generated by build_graphics.py - do not edit. */',
             '#ifndef _COLOR_PROFILES_H', '#define _COLOR_PROFILES_H',
             '#include <stdint.h>',
             f'#define FIELD_PROFILES {len(FIELDS)}',
             f'#define ARMY_PROFILES {len(ARMIES)}',
             ]
    for symbol, values in [('field_profiles', [p[2] for p in FIELDS]),
                           ('army_profiles', [p[2] for p in ARMIES])]:
        lines.append(f'static const uint16_t {symbol}[{len(values)}][16] = {{')
        lines += ['    {' + ', '.join(f'0x{v:03X}' for v in colors) + '},' for colors in values]
        lines.append('};')
    lines.append('static const uint8_t field_art[FIELD_PROFILES] = {' +
                 ', '.join(str(p[3]) for p in FIELDS) + '};')
    for symbol, names in [('field_names', [p[1] for p in FIELDS]),
                          ('army_names', [p[1] for p in ARMIES])]:
        lines.append(f'static const char* const {symbol}[{len(names)}] = {{')
        lines += [f'    "{name.upper()}",' for name in names]
        lines.append('};')
    return '\n'.join(lines + ['#endif', ''])
